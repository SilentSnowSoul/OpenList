func TestEnteListCollections(t *testing.T) {
	m := newMockWithAccount(t)
	logs := captureLogs(t)

	d := newTestDriver(t, accountAddition("Fxacct1", m.URL))
	objs := listRoot(t, d)
	if got, want := names(objs), []string{"旅行 2024"}; !slices.Equal(got, want) {
		t.Errorf("root names = %q, want %q", got, want)
	}
	for _, o := range objs {
		if !o.IsDir() {
			t.Errorf("%s is not a folder", o.GetName())
		}
	}
	// The shared album cannot be opened without secret_key: it is skipped with a
	// warning naming the album, not silently dropped.
	if got := logs.String(); !strings.Contains(got, "9002") {
		t.Errorf("logs = %q, want a warning naming album 9002", got)
	}
	if urls := m.urls(); !slices.Contains(urls, "/collections/v2?sinceTime=0") {
		t.Errorf("urls = %q, want /collections/v2?sinceTime=0", urls)
	}
	if got := m.requests()[0].header.Get("X-Auth-Token"); got != "Fxacct1" {
		t.Errorf("X-Auth-Token = %q, want Fxacct1", got)
	}
}

