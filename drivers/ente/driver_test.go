type seenRequest struct {
	url    string
	header http.Header
}

type mockEnte struct {
	*httptest.Server

	mu          sync.Mutex
	seen        []seenRequest
	collections string
	// pages is indexed by "<collectionID>:<sinceTime>"; a request for a page
	// that is not listed fails, which pins down pagination termination.
	pages    map[string]string
	bin      map[string][]byte
	fragment int
	// keyAttrs is served from /users/session-validity/v2; empty means 401
	// (invalid token).
	keyAttrs string
}

func newMockEnte(t *testing.T) *mockEnte {
	t.Helper()
	m := &mockEnte{pages: map[string]string{}, bin: map[string][]byte{}}
	m.Server = httptest.NewServer(http.HandlerFunc(m.serve))
	t.Cleanup(m.Server.Close)
	return m
}

func writeJSON(w http.ResponseWriter, v any) {
	w.Header().Set("Content-Type", "application/json")
	_ = json.NewEncoder(w).Encode(v)
}

func (m *mockEnte) serve(w http.ResponseWriter, r *http.Request) {
	m.mu.Lock()
	m.seen = append(m.seen, seenRequest{url: r.URL.String(), header: r.Header.Clone()})
	m.mu.Unlock()

	switch {
	case strings.HasPrefix(r.URL.Path, "/bin/"):
		key := strings.TrimPrefix(r.URL.Path, "/bin/")
		body, ok := m.bin[key]
		if !ok {
			http.Error(w, "unknown bin "+key, http.StatusNotFound)
			return
		}
		if m.fragment > 0 {
			// Write in small fragments so the decryptor cannot rely on network
			// chunk boundaries.
			for off := 0; off < len(body); off += m.fragment {
				end := min(off+m.fragment, len(body))
				if _, err := w.Write(body[off:end]); err != nil {
					return
				}
				w.(http.Flusher).Flush()
			}
			return
		}
		_, _ = w.Write(body)
	case r.URL.Path == "/users/session-validity/v2":
		if m.keyAttrs == "" {
			http.Error(w, "invalid token", http.StatusUnauthorized)
			return
		}
		writeJSON(w, json.RawMessage(m.keyAttrs))
	case r.URL.Path == "/collections/v2":
		w.Header().Set("Content-Type", "application/json")
		_, _ = io.WriteString(w, m.collections)
	case r.URL.Path == "/collections/v2/diff":
		key := r.URL.Query().Get("collectionID") + ":" + r.URL.Query().Get("sinceTime")
		body, ok := m.pages[key]
		if !ok {
			http.Error(w, "unexpected request "+key, http.StatusInternalServerError)
			return
		}
		w.Header().Set("Content-Type", "application/json")
		_, _ = io.WriteString(w, body)
	case strings.HasPrefix(r.URL.Path, "/files/download/v3/"):
		writeJSON(w, map[string]string{"url": m.URL + "/bin/file"})
	case strings.HasPrefix(r.URL.Path, "/files/thumbnail/v3/"):
		writeJSON(w, map[string]string{"url": m.URL + "/bin/thumb"})
	default:
		http.Error(w, "unexpected path "+r.URL.Path, http.StatusNotFound)
	}
}

func (m *mockEnte) requests() []seenRequest {
	m.mu.Lock()
	defer m.mu.Unlock()
	out := make([]seenRequest, len(m.seen))
	copy(out, m.seen)
	return out
}

func (m *mockEnte) urls() []string {
	reqs := m.requests()
	out := make([]string, 0, len(reqs))
	for _, r := range reqs {
		out = append(out, r.url)
	}
	return out
}

