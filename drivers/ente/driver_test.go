func TestEnteAdminForm(t *testing.T) {
	info, ok := op.GetDriverInfoMap()["Ente"]
	if !ok {
		t.Fatal("Ente missing from the driver info map")
	}
	items := map[string]driver.Item{}
	for _, it := range info.Additional {
		items[it.Name] = it
	}
	for name, required := range map[string]bool{
		"email": false, "password": false, "two_fa_secret": false,
		"token": false, "master_key": false, "secret_key": false, "show_hidden": false, "endpoint": false,
	} {
		it, ok := items[name]
		if !ok {
			t.Errorf("admin form is missing %q", name)
			continue
		}
		if it.Required != required {
			t.Errorf("%s required = %v, want %v", name, it.Required, required)
		}
	}
	if got := items["endpoint"].Default; got != "https://api.ente.com" {
		t.Errorf("endpoint default = %q, want https://api.ente.com", got)
	}
	if got := items["show_hidden"].Default; got != "false" {
		t.Errorf("show_hidden default = %q, want false", got)
	}
	if got := items["root_folder_path"].Default; got != "root" {
		t.Errorf("root_folder_path default = %q, want root", got)
	}
}
