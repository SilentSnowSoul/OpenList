// captureLogs redirects the global logrus output so tests can assert warnings.
func captureLogs(t *testing.T) *bytes.Buffer {
	t.Helper()
	buf := &bytes.Buffer{}
	prevOut := log.StandardLogger().Out
	prevFmt := log.StandardLogger().Formatter
	log.SetOutput(buf)
	log.SetFormatter(&log.TextFormatter{DisableColors: true})
	t.Cleanup(func() {
		log.SetOutput(prevOut)
		log.SetFormatter(prevFmt)
	})
	return buf
}

func accountAddition(token, endpoint string) Addition {
	return Addition{
		RootPath:  driver.RootPath{RootFolderPath: "root"},
		Endpoint:  endpoint,
		Token:     token,
		MasterKey: masterKeyB64,
	}
}

func newTestDriver(t *testing.T, addition Addition) *Ente {
	t.Helper()
	d := &Ente{Addition: addition}
	if err := d.Init(context.Background()); err != nil {
		t.Fatalf("Init: %v", err)
	}
	d.SetStorage(model.Storage{MountPath: "/ente"})
	return d
}

// newMockWithAccount wires a mock server carrying album A (with f201/f202 and
// their tombstones), the hidden album and shared album B.
func newMockWithAccount(t *testing.T) *mockEnte {
	t.Helper()
	m := newMockEnte(t)
	m.collections = collectionsJSON(t, []EnteCollection{albumA(), albumB(), albumHidden()})
	// Page 1 advances the watermark to 1100; page 2 only carries entries older
	// than 1100, so the watermark stops advancing and pagination must terminate.
	m.pages["9001:0"] = pageJSON(t, []EnteDiffFile{f201(), f203Deleted()}, true)
	m.pages["9001:1100"] = pageJSON(t, []EnteDiffFile{f202(), f204Removed()}, false)
	m.bin["file"] = mustB64(t, stream201Cipher)
	m.bin["thumb"] = mustB64(t, stream201Cipher)
	return m
}

