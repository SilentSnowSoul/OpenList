type seenRequest struct {
	url    string
	header http.Header
}

type mockEnte struct {
	*httptest.Server

	mu          sync.Mutex
	seen        []seenRequest
	pages       map[string]string
	infoCode    int
	failCode    int
	failBody    string
	deviceToken string
	bin         map[string][]byte
	fragment    int
}

func newMockEnte(t *testing.T) *mockEnte {
	t.Helper()
	m := &mockEnte{
		pages:    map[string]string{},
		bin:      map[string][]byte{},
		infoCode: 200,
	}
	m.Server = httptest.NewServer(http.HandlerFunc(m.serve))
	t.Cleanup(m.Server.Close)
	return m
}

func writeJSON(w http.ResponseWriter, v any) {
	w.Header().Set("Content-Type", "application/json")
	_ = json.NewEncoder(w).Encode(v)
}

func (m *mockEnte) serve(w http.ResponseWriter, r *http.Request) {
	m.mu.Lock()
	m.seen = append(m.seen, seenRequest{url: r.URL.String(), header: r.Header.Clone()})
	m.mu.Unlock()

	if m.deviceToken != "" {
		w.Header().Set("X-Link-Device-Token", m.deviceToken)
	}

	switch {
	case strings.HasPrefix(r.URL.Path, "/bin/"):
		key := strings.TrimPrefix(r.URL.Path, "/bin/")
		body, ok := m.bin[key]
		if !ok {
			http.Error(w, "unknown bin "+key, http.StatusNotFound)
			return
		}
		if m.fragment > 0 {
			// Write in small fragments so the decryptor cannot rely on network
			// chunk boundaries.
			for off := 0; off < len(body); off += m.fragment {
				end := off + m.fragment
				if end > len(body) {
					end = len(body)
				}
				if _, err := w.Write(body[off:end]); err != nil {
					return
				}
				w.(http.Flusher).Flush()
			}
			return
		}
		_, _ = w.Write(body)
	case r.URL.Path == "/public-collection/info":
		w.WriteHeader(m.infoCode)
		_, _ = io.WriteString(w, "{}")
	case r.URL.Path == "/public-collection/diff":
		if m.failCode != 0 {
			w.WriteHeader(m.failCode)
			_, _ = io.WriteString(w, m.failBody)
			return
		}
		since := r.URL.Query().Get("sinceTime")
		body, ok := m.pages[since]
		if !ok {
			http.Error(w, "unexpected request sinceTime="+since, http.StatusInternalServerError)
			return
		}
		w.Header().Set("Content-Type", "application/json")
		_, _ = io.WriteString(w, body)
	case strings.HasPrefix(r.URL.Path, "/public-collection/files/download/v3/"):
		id := strings.TrimPrefix(r.URL.Path, "/public-collection/files/download/v3/")
		writeJSON(w, map[string]string{"url": m.URL + "/bin/file-" + id})
	case strings.HasPrefix(r.URL.Path, "/public-collection/files/thumbnail/v3/"):
		id := strings.TrimPrefix(r.URL.Path, "/public-collection/files/thumbnail/v3/")
		writeJSON(w, map[string]string{"url": m.URL + "/bin/thumb-" + id})
	default:
		http.Error(w, "unexpected path "+r.URL.Path, http.StatusNotFound)
	}
}

func (m *mockEnte) requests() []seenRequest {
	m.mu.Lock()
	defer m.mu.Unlock()
	out := make([]seenRequest, len(m.seen))
	copy(out, m.seen)
	return out
}

func (m *mockEnte) urls() []string {
	reqs := m.requests()
	out := make([]string, 0, len(reqs))
	for _, r := range reqs {
		out = append(out, r.url)
	}
	return out
}

