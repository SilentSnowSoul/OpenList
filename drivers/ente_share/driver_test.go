func TestEnteShareList(t *testing.T) {
	m := newMockEnte(t)
	// Page 1 advances the watermark to 1100; page 2 only carries entries older
	// than 1100, so the watermark stops advancing and pagination must terminate.
	m.pages["0"] = pageJSON(t, []ente.EnteDiffFile{f101(), f103Deleted(), f105()}, true)
	m.pages["1100"] = pageJSON(t, []ente.EnteDiffFile{f102(), f104Removed()}, true)

	d := newTestDriver(t, m, func() Addition {
		a := shareAddition("Fxtoken1")
		a.Endpoint = m.URL
		return a
	}())

	objs, err := d.List(apiCtx(), &model.Object{Path: d.GetRootPath()}, model.ListArgs{ReqPath: "/"})
	if err != nil {
		t.Fatal(err)
	}
	if len(objs) != 3 {
		t.Fatalf("want 3 objs, got %d: %v", len(objs), objs)
	}
	bySize := map[int64]model.Obj{}
	for _, o := range objs {
		bySize[o.GetSize()] = o
	}
	if o := bySize[12328]; o.GetName() != "日落.jpg" {
		t.Errorf("size 12328 name = %q, want 日落.jpg", o.GetName())
	} else if want := "2024-10-05T06:51:51.111Z"; o.ModTime().UTC().Format("2006-01-02T15:04:05.000Z") != want {
		t.Errorf("size 12345 modified = %v, want %s", o.ModTime(), want)
	}
	if o := bySize[205]; o.GetName() != "日落 (2).jpg" {
		t.Errorf("size 205 name = %q, want 日落 (2).jpg", o.GetName())
	} else if want := "2024-10-04T00:00:00.000Z"; o.ModTime().UTC().Format("2006-01-02T15:04:05.000Z") != want {
		t.Errorf("size 222 modified = %v, want %s", o.ModTime(), want)
	}
	// editedTime == 0 falls back to creationTime; editedName overrides title.
	if o := bySize[999982]; o.GetName() != "holiday video.mp4" {
		t.Errorf("size 999982 name = %q, want holiday video.mp4", o.GetName())
	} else if want := "2024-10-06T13:43:42.222Z"; o.ModTime().UTC().Format("2006-01-02T15:04:05.000Z") != want {
		t.Errorf("size 999982 modified = %v, want %s", o.ModTime(), want)
	}

	for _, o := range objs {
		if o.IsDir() {
			t.Errorf("%s: must not be a dir", o.GetName())
		}
		if u, ok := model.GetUrl(o); ok && u != "" {
			t.Errorf("%s: NoLinkURL driver must not expose a url, got %q", o.GetName(), u)
		}
	}

	names := make([]string, 0, len(objs))
	for _, o := range objs {
		names = append(names, o.GetName())
	}
	// Files are listed name-ascending, matching the worker's default order.
	if want := []string{"holiday video.mp4", "日落 (2).jpg", "日落.jpg"}; !reflect.DeepEqual(names, want) {
		t.Errorf("names = %v, want %v", names, want)
	}

	// Exactly two pages; a third request would fail the mock.
	urls := m.urls()
	if len(urls) != 2 {
		t.Fatalf("requests = %v, want exactly 2", urls)
	}
	if !strings.HasSuffix(urls[0], "/public-collection/diff?sinceTime=0") {
		t.Errorf("urls[0] = %q", urls[0])
	}
	if !strings.HasSuffix(urls[1], "sinceTime=1100") {
		t.Errorf("urls[1] = %q", urls[1])
	}
	h := m.requests()[0].header
	if got := h.Get("X-Auth-Access-Token"); got != "Fxtoken1" {
		t.Errorf("X-Auth-Access-Token = %q, want Fxtoken1", got)
	}
	if got := h.Get("X-Client-Package"); got != "io.ente.photos" {
		t.Errorf("X-Client-Package = %q, want io.ente.photos", got)
	}
	if strings.Contains(h.Get("User-Agent"), "Go-http-client") {
		t.Errorf("User-Agent must not be Go's default, got %q", h.Get("User-Agent"))
	}
}

func TestEnteShareGet(t *testing.T) {
	m := newMockEnte(t)
	m.pages["0"] = pageJSON(t, []ente.EnteDiffFile{f101(), f102()}, false)

	d := newTestDriver(t, m, func() Addition {
		a := shareAddition("Fxtoken2")
		a.Endpoint = m.URL
		return a
	}())

	obj, err := d.Get(apiCtx(), "/日落.jpg")
	if err != nil {
		t.Fatal(err)
	}
	if obj.GetName() != "日落.jpg" || obj.GetSize() != 12328 {
		t.Errorf("get = %s size %d", obj.GetName(), obj.GetSize())
	}
	// Get must build the same thumbnail URL as List: the signed path is the
	// mount path plus the file name, never the full object path.
	thumb, ok := model.GetThumb(obj)
	if !ok {
		t.Fatal("日落.jpg must carry a thumbnail")
	}
	if u, err := url.Parse(thumb); err != nil {
		t.Fatal(err)
	} else if want := "/p/ente_share/日落.jpg"; u.Path != want {
		t.Errorf("get thumb path = %q, want %q", u.Path, want)
	} else if !strings.Contains(u.RawQuery, "type=thumb&sign=") {
		t.Errorf("get thumb query = %q, want type=thumb&sign=", u.RawQuery)
	}

	root, err := d.Get(apiCtx(), "/")
	if err != nil {
		t.Fatal(err)
	}
	if !root.IsDir() {
		t.Error("root must be a dir")
	}

	if _, err := d.Get(apiCtx(), "/nope.jpg"); err == nil {
		t.Error("want not-found error")
	}
}

func TestEnteShareLinkStream(t *testing.T) {
	m := newMockEnte(t)
	m.pages["0"] = pageJSON(t, []ente.EnteDiffFile{f105()}, false)
	m.bin["file-105"] = mustB64(t, f105StreamCipher)
	m.fragment = 7

	d := newTestDriver(t, m, func() Addition {
		a := shareAddition("Fxtoken4")
		a.Endpoint = m.URL
		return a
	}())

	objs, err := d.List(apiCtx(), &model.Object{Path: d.GetRootPath()}, model.ListArgs{ReqPath: "/"})
	if err != nil {
		t.Fatal(err)
	}
	if len(objs) != 1 {
		t.Fatalf("want 1 obj, got %d", len(objs))
	}

	link, err := d.Link(apiCtx(), objs[0], model.LinkArgs{})
	if err != nil {
		t.Fatal(err)
	}
	if link.URL != "" {
		t.Errorf("NoLinkURL driver must not return a URL, got %q", link.URL)
	}
	if link.ContentLength != 999982 {
		t.Errorf("ContentLength = %d, want plaintext size 999982", link.ContentLength)
	}
	if link.RangeReader == nil {
		t.Fatal("RangeReader is nil")
	}

	rc, err := link.RangeReader.RangeRead(apiCtx(), http_range.Range{Length: -1})
	if err != nil {
		t.Fatal(err)
	}
	defer rc.Close()
	got, err := io.ReadAll(rc)
	if err != nil {
		t.Fatal(err)
	}
	want := append([]byte("hello ente"), bytes.Repeat([]byte{0xab}, 300)...)
	want = append(want, []byte("tail")...)
	if !bytes.Equal(got, want) {
		t.Errorf("plaintext mismatch: got %d bytes, want %d", len(got), len(want))
	}

	urls := m.urls()
	wantURLs := []string{
		"/public-collection/diff?sinceTime=0",
		"/public-collection/files/download/v3/105",
		"/bin/file-105",
	}
	if !reflect.DeepEqual(urls, wantURLs) {
		t.Errorf("requests = %v, want %v", urls, wantURLs)
	}
	// The presigned S3 fetch must carry no ente headers at all.
	binReq := m.requests()[2]
	if _, ok := binReq.header["X-Client-Package"]; ok {
		t.Error("presigned fetch must not send X-Client-Package")
	}
	if _, ok := binReq.header["X-Auth-Access-Token"]; ok {
		t.Error("presigned fetch must not send X-Auth-Access-Token")
	}
	if binReq.header.Get("User-Agent") != "" {
		t.Errorf("presigned fetch must not send a User-Agent, got %q", binReq.header.Get("User-Agent"))
	}
}

