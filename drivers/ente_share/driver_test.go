func apiCtx() context.Context {
	return context.WithValue(context.Background(), conf.ApiUrlKey, "http://127.0.0.1:5244")
}

func newTestDriver(t *testing.T, m *mockEnte, addition Addition) *EnteShare {
	t.Helper()
	d := &EnteShare{Addition: addition}
	if err := d.Init(context.Background()); err != nil {
		t.Fatalf("Init: %v", err)
	}
	// Never touch the database in unit tests.
	d.saveStorage = func() {}
	d.SetStorage(model.Storage{MountPath: "/ente_share"})
	return d
}

func shareAddition(token string) Addition {
	return Addition{
		ShareURL: "https://share.ente.io/c/" + token + "#" + testCollectionKeyB58,
	}
}

func mustB64(t *testing.T, s string) []byte {
	t.Helper()
	b, err := base64.StdEncoding.DecodeString(s)
	if err != nil {
		t.Fatalf("bad base64 fixture %q: %v", s, err)
	}
	return b
}

