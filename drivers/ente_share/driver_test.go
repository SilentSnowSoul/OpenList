func TestEnteShareRegistration(t *testing.T) {
	ctor, err := op.GetDriver("EnteShare")
	if err != nil {
		t.Fatal(err)
	}
	cfg := ctor().Config()
	if !cfg.OnlyProxy {
		t.Error("OnlyProxy must be true")
	}
	if !cfg.NoUpload {
		t.Error("NoUpload must be true")
	}
	if !cfg.NoLinkURL {
		t.Error("NoLinkURL must be true")
	}
	if !cfg.MustProxy() {
		t.Error("MustProxy must be true")
	}
	if cfg.DefaultRoot != "" {
		t.Errorf("DefaultRoot = %q, want empty", cfg.DefaultRoot)
	}

	info, ok := op.GetDriverInfoMap()["EnteShare"]
	if !ok {
		t.Fatal("EnteShare missing from driverInfoMap")
	}
	var names []string
	for _, item := range info.Additional {
		names = append(names, item.Name)
	}
	for _, want := range []string{"share_url", "endpoint"} {
		if !slices.Contains(names, want) {
			t.Errorf("additional items %v missing %q", names, want)
		}
	}
	if slices.Contains(names, "device_token") {
		t.Error("device_token must be hidden from the admin form")
	}
}
